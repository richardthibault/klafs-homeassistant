window.customIconsets = window.customIconsets || {};
window.customIconsets["klafs"] = (name) => {
  const svgString = KLAFS_ICONS[name];
  return svgString ? parseSvgIcon(svgString) : null;
};

window.customIcons = window.customIcons || {};
window.customIcons["klafs"] = {
  getIcon: (name) => {
    const svgString = KLAFS_ICONS[name];
    return svgString ? parseSvgIcon(svgString) : null;
  }
};

